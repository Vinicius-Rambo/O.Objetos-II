public class Vendedor {
    private int codigo;
    private String nome;
    private String contato;
    private String email;
    private String cpf;
    private String numCrasha;
    private String anoAdmissao;
    private String cargo;

    //Codigo
    public int getCodigo() {
        return codigo;
    }

    public void setCodigo(int codigo) {
        this.codigo = codigo;
    }

    //Nome
    public String getNome() {
        return nome;
    }
    public void setNome(String nome) {
        this.nome = nome;
    }

    //Contato
    public String getContato() {
        return contato;
    }

    public void setContato(String contato) {
        this.contato = contato;
    }

    //E-mail
    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    //Cpf
    public String getCpf() {
        return cpf;
    }

    public void setCpf(String cpf) {
        this.cpf = cpf;
    }

    //Crasha
    public String getNumCrasha() {
        return numCrasha;
    }
    public void setNumCrasha(String numCrasha) {
        this.numCrasha = numCrasha;
    }

    //Ano Admissao
    public String getAnoAdmissao() {
        return anoAdmissao;
    }
    public void setAnoAdmissao(String anoAdimissao) {
        this.anoAdmissao = anoAdimissao;
    }

    //Cargo
    public String getCargo() {
        return cargo;
    }
    public void setCargo(String cargo) {
        this.cargo = cargo;
    }


    
}
